#!/usr/bin/env bash
# Mirror kit/pilot documents into docs/ at the refs in kit.ref, and generate the CLI
# reference from `adlc --help`. The kit is the source of truth; nothing here is edited by hand.
# `--check` re-syncs into a temp dir and fails if docs/ differs (CI).
set -euo pipefail
ROOT="$(cd "$(dirname "$0")/.." && pwd)"; cd "$ROOT"
# shellcheck disable=SC1091
source kit.ref
MODE="${1:-write}"
WORK="$(mktemp -d)"; trap 'rm -rf "$WORK"' EXIT
git clone -q --depth 1 --branch "$KIT_REF" "https://github.com/$KIT_REPO.git" "$WORK/kit"
git clone -q "https://github.com/$PILOT_REPO.git" "$WORK/pilot" && git -C "$WORK/pilot" checkout -q "$PILOT_REF"
OUT="$WORK/docs"; mkdir -p "$OUT"

hdr() { # $1 repo $2 ref $3 path
  printf '!!! info "Mirrored, do not edit here"\n    Source: [`%s`](https://github.com/%s/blob/%s/%s) at `%s`. Change it there; `make sync` brings it back.\n\n' "$3" "$1" "$2" "$3" "$2"
}
# Rewrite the kit's own relative links to where they land on this site.
relink() {
  sed -E \
    -e 's#\(monitor/RUNBOOK\.md\)#(../operate/runbook.md)#g' \
    -e 's#\(policy/CONTEXT_CONTRACT\.md\)#(../reference/contract.md)#g' \
    -e 's#\(INSTALL_MINUTES\.md\)#(../operate/install-costs.md)#g' \
    -e 's#\(PINS\.md\)#(../reference/pins.md)#g' \
    -e 's#\(CHANGELOG\.md\)#(../reference/changelog.md)#g' \
    -e 's#\(ADOPT\.md\)#(../adopt/index.md)#g' \
    -e 's#\(DECISIONS\.md\)#(https://github.com/'"$PILOT_REPO"'/blob/'"$PILOT_REF"'/DECISIONS.md)#g' \
    -e 's#\(results/REPORT\.md\)#(report.md)#g' \
    -e 's#\(results/scorecard\.md\)#(https://github.com/'"$PILOT_REPO"'/blob/'"$PILOT_REF"'/results/scorecard.md)#g' \
    -e 's#\(results/spotcheck\.md\)#(https://github.com/'"$PILOT_REPO"'/blob/'"$PILOT_REF"'/results/spotcheck.md)#g' \
    -e 's#\(DECISION_ADR\.md\)#(adr.md)#g'
}
mirror() { # $1 src-root $2 repo $3 ref $4 path $5 dest
  mkdir -p "$(dirname "$OUT/$5")"
  { hdr "$2" "$3" "$4"; relink < "$1/$4"; } > "$OUT/$5"
}
mirror "$WORK/kit"   "$KIT_REPO"   "$KIT_REF"   ADOPT.md                   adopt/index.md
mirror "$WORK/kit"   "$KIT_REPO"   "$KIT_REF"   template/ROUTING.md        how-it-works/routing.md
mirror "$WORK/kit"   "$KIT_REPO"   "$KIT_REF"   monitor/RUNBOOK.md         operate/runbook.md
mirror "$WORK/kit"   "$KIT_REPO"   "$KIT_REF"   INSTALL_MINUTES.md         operate/install-costs.md
mirror "$WORK/kit"   "$KIT_REPO"   "$KIT_REF"   policy/CONTEXT_CONTRACT.md reference/contract.md
mirror "$WORK/kit"   "$KIT_REPO"   "$KIT_REF"   harness/EVENTS_SCHEMA.md   reference/events-schema.md
mirror "$WORK/kit"   "$KIT_REPO"   "$KIT_REF"   PINS.md                    reference/pins.md
mirror "$WORK/kit"   "$KIT_REPO"   "$KIT_REF"   CHANGELOG.md               reference/changelog.md
mirror "$WORK/pilot" "$PILOT_REPO" "$PILOT_REF" DECISION_ADR.md            decide/adr.md
mirror "$WORK/pilot" "$PILOT_REPO" "$PILOT_REF" results/REPORT.md          decide/report.md

# CLI reference, generated from the pinned kit itself.
export GRAPHIFY_BACKEND=none UV_TOOL_DIR="$WORK/uvtool" UV_TOOL_BIN_DIR="$WORK/uvbin"
uv tool install -q --python 3.12 "git+https://github.com/$KIT_REPO@$KIT_REF" >/dev/null 2>&1
ADLC="$WORK/uvbin/adlc"
{
  printf '# CLI reference\n\n!!! info "Generated"\n    Output of `adlc --help` for kit `%s`. Regenerated by `make sync`.\n\n```text\n' "$KIT_REF"
  "$ADLC" --help
  printf '```\n'
  for sub in init doctor lint baseline stale query federate eval regress scorecard upgrade pins guard_hook force_hook; do
    printf '\n## `adlc %s`\n\n```text\n' "$sub"; "$ADLC" "$sub" --help 2>&1 || true; printf '```\n'
  done
} > "$OUT/reference/cli.md"

# Version marker on the landing page: rendered into $OUT like every other page, so
# --check compares it instead of healing it.
python3 - "$ROOT/docs/index.md" "$OUT/index.md" "$KIT_REF" "$PILOT_REF" <<'PY'
import re,sys,pathlib
s=pathlib.Path(sys.argv[1]).read_text()
s=re.sub(r'(<!-- adlc:kit-ref -->).*?(<!-- /adlc:kit-ref -->)', rf'\g<1>`{sys.argv[3]}`\g<2>', s)
s=re.sub(r'(<!-- adlc:pilot-ref -->).*?(<!-- /adlc:pilot-ref -->)', rf'\g<1>`{sys.argv[4][:7]}`\g<2>', s)
pathlib.Path(sys.argv[2]).write_text(s)
PY

if [ "$MODE" = "--check" ]; then
  fail=0
  while IFS= read -r -d '' f; do rel="${f#$OUT/}"; cmp -s "$f" "docs/$rel" || { echo "DRIFT docs/$rel"; fail=1; }; done < <(find "$OUT" -type f -print0)
  [ $fail -eq 0 ] && echo "sync: docs match $KIT_REPO@$KIT_REF and $PILOT_REPO@$PILOT_REF" || exit 1
else
  (cd "$OUT" && find . -type f -print0) | while IFS= read -r -d '' f; do mkdir -p "docs/$(dirname "$f")"; cp "$OUT/$f" "docs/$f"; done
  echo "sync: wrote $(find "$OUT" -type f | wc -l | tr -d ' ') mirrored/generated pages"
fi
